const dictionaries = { en, it } as const;
export type Lang = keyof typeof dictionaries;

export function detectLang(preferred?: string): Lang {
  const candidates = [preferred, ...(typeof navigator === 'undefined' ? [] : navigator.languages)];
  for (const candidate of candidates) {
    const base = candidate?.slice(0, 2).toLowerCase();
    if (base && base in dictionaries) return base as Lang;
  }
  return 'en';
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  const dictionary = dictionaries[lang];
  return (key, vars) => {
    const text: string = dictionary[key] ?? en[key];
    return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? '')) : text;
  };
}
